'use strict';

/**
 * End-user setup helpers for the terminal CLI and Claude Code integration.
 *
 * Everything here writes outside the repository: a `flow` launcher, a stable
 * copy of the CLI in Flow's app-data directory, and the user-level Claude
 * skill/command. It never executes a shell command and never touches a
 * workspace folder.
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const claude = require('./claudeIntegration.cjs');

const SHIM_MARKER = 'Flow CLI launcher (generated by the Flow VS Code extension)';

/** CLI files that must travel together; paths are relative to the extension. */
const CLI_SOURCES = [
  ['cli/flow.mjs', 'cli/flow.mjs'],
  ['src/extension/protocol.cjs', 'src/extension/protocol.cjs'],
  ['src/extension/claudeIntegration.cjs', 'src/extension/claudeIntegration.cjs'],
];

function pathsFor(platform) {
  return platform === 'win32' ? path.win32 : path.posix;
}

function homeDir(env, platform) {
  if (platform === 'win32') {
    return env.USERPROFILE || env.HOME || os.homedir();
  }
  return env.HOME || env.USERPROFILE || os.homedir();
}

function splitPath(pathEnv, platform) {
  if (typeof pathEnv !== 'string') return [];
  return pathEnv.split(platform === 'win32' ? ';' : ':');
}

function stripQuotes(value) {
  return value.replace(/^"(.*)"$/, '$1');
}

function normalizedPath(value, platform) {
  const resolved = path.resolve(stripQuotes(value));
  const trimmed = resolved.replace(/[\\/]+$/, '');
  return platform === 'win32' ? trimmed.toLowerCase() : trimmed;
}

function findExecutable(name, pathEnv, platform = process.platform) {
  const p = pathsFor(platform);
  const names =
    platform === 'win32'
      ? [`${name}.exe`, `${name}.cmd`, `${name}.bat`, name]
      : [name];
  for (const entry of splitPath(pathEnv, platform)) {
    if (!entry) continue;
    for (const candidateName of names) {
      const candidate = p.join(stripQuotes(entry), candidateName);
      try {
        const stat = fs.statSync(candidate);
        if (!stat.isFile()) continue;
        if (platform !== 'win32' && (stat.mode & 0o111) === 0) continue;
        return candidate;
      } catch {
        /* not in this directory */
      }
    }
  }
  return null;
}

function nodeExecutableOnPath(pathEnv, platform = process.platform) {
  return findExecutable('node', pathEnv, platform);
}

function isDirectoryOnPath(dir, pathEnv, platform = process.platform) {
  const target = normalizedPath(dir, platform);
  return splitPath(pathEnv, platform).some(
    (entry) => entry && normalizedPath(entry, platform) === target,
  );
}

function defaultInstallDir({ platform = process.platform, env = process.env, homedir } = {}) {
  if (typeof env.FLOW_CLI_DIR === 'string' && env.FLOW_CLI_DIR.trim()) {
    return path.resolve(env.FLOW_CLI_DIR.trim());
  }
  const p = pathsFor(platform);
  const home = homedir || homeDir(env, platform);
  if (platform === 'win32') {
    const base = env.LOCALAPPDATA || p.join(home, 'AppData', 'Local');
    return p.join(base, 'flow', 'bin');
  }
  return p.join(home, '.local', 'bin');
}

function installPaths(options = {}) {
  const platform = options.platform || process.platform;
  const dir = defaultInstallDir({ ...options, platform });
  const file = pathsFor(platform).join(
    dir,
    platform === 'win32' ? 'flow.cmd' : 'flow',
  );
  return { dir, file };
}

function toolsDir(appDataDir) {
  return path.join(appDataDir, 'tools');
}

function cliEntryPath(appDataDir) {
  return path.join(toolsDir(appDataDir), 'cli', 'flow.mjs');
}

function readVersion(extensionPath) {
  try {
    const raw = fs.readFileSync(path.join(extensionPath, 'package.json'), 'utf8');
    return JSON.parse(raw).version || '0.0.0';
  } catch {
    return '0.0.0';
  }
}

function writeFileAtomic(file, content, mode) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.${crypto.randomBytes(4).toString('hex')}.tmp`;
  fs.writeFileSync(tmp, content, { mode });
  try {
    fs.chmodSync(tmp, mode);
  } catch {
    /* Windows ignores POSIX modes */
  }
  fs.renameSync(tmp, file);
}

/** Copies the CLI into a stable location so extension updates do not break it. */
function copyCliTools({ extensionPath, appDataDir, version }) {
  if (!extensionPath) throw new Error('The Flow extension path is missing.');
  if (!appDataDir) throw new Error('The Flow app-data path is missing.');

  const tools = toolsDir(appDataDir);
  for (const [source, target] of CLI_SOURCES) {
    const from = path.join(extensionPath, source);
    const to = path.join(tools, target);
    let content;
    try {
      content = fs.readFileSync(from);
    } catch {
      throw new Error(`The extension is missing ${source}. Reinstall Flow.`);
    }
    writeFileAtomic(to, content, 0o644);
  }

  writeFileAtomic(
    path.join(tools, 'package.json'),
    `${JSON.stringify(
      {
        name: 'flow-docs-cli',
        version: version || '0.0.0',
        private: true,
        type: 'module',
        engines: { node: '>=18' },
      },
      null,
      2,
    )}\n`,
    0o644,
  );

  return { toolsDir: tools, cliPath: cliEntryPath(appDataDir) };
}

function refreshCliTools({ extensionPath, appDataDir, version } = {}) {
  if (!appDataDir || !fs.existsSync(cliEntryPath(appDataDir))) {
    return { refreshed: false, reason: 'not-installed' };
  }
  try {
    copyCliTools({ extensionPath, appDataDir, version });
    return { refreshed: true };
  } catch (error) {
    return { refreshed: false, reason: error.message };
  }
}

function shQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

function quoteForShell(value, platform) {
  return platform === 'win32' ? `"${String(value).replace(/"/g, '')}"` : shQuote(value);
}

function formatArg(value, platform) {
  const text = String(value);
  if (!/[\s"']/.test(text)) return text;
  return quoteForShell(text, platform);
}

function formatCommand(args, platform = process.platform) {
  return args.map((arg) => formatArg(arg, platform)).join(' ');
}

function renderPosixShim(cliPath) {
  return `#!/bin/sh
# ${SHIM_MARKER}
if ! command -v node >/dev/null 2>&1; then
  echo "flow: Node.js is required but was not found on PATH." >&2
  exit 127
fi
exec node ${shQuote(cliPath)} "$@"
`;
}

function renderWindowsShim(cliPath) {
  const escaped = String(cliPath).replace(/%/g, '%%').replace(/"/g, '');
  return `@echo off\r
rem ${SHIM_MARKER}\r
where node >nul 2>nul\r
if errorlevel 1 (\r
  echo flow: Node.js is required but was not found on PATH. 1>&2\r
  exit /b 127\r
)\r
node "${escaped}" %*\r
`;
}

function pathGuidance(dir, platform) {
  if (platform === 'win32') {
    return {
      onPathHint: `Add this folder to your user PATH: ${dir}`,
      command: `set PATH=%PATH%;${dir}`,
    };
  }
  return {
    onPathHint: `Add this line to your shell profile (~/.bashrc or ~/.zshrc):`,
    command: `export PATH=${shQuote(dir)}:"$PATH"`,
  };
}

function installCli(options = {}) {
  const platform = options.platform || process.platform;
  const env = options.env || process.env;
  const homedir = options.homedir || homeDir(env, platform);
  const extensionPath = options.extensionPath;
  const appDataDir = options.appDataDir;
  const force = options.force === true;
  const { dir, file: shimPath } = installPaths({ platform, env, homedir });

  if (!extensionPath || !appDataDir) {
    return { ok: false, errors: ['The Flow extension could not locate its bundled CLI.'] };
  }

  let existing = null;
  try {
    existing = fs.readFileSync(shimPath, 'utf8');
  } catch {
    existing = null;
  }
  if (existing !== null && !existing.includes(SHIM_MARKER) && !force) {
    return {
      ok: false,
      conflict: true,
      shimPath,
      errors: [
        `${shimPath} already exists and was not created by Flow. Remove it or choose another folder with FLOW_CLI_DIR.`,
      ],
    };
  }

  const copied = copyCliTools({
    extensionPath,
    appDataDir,
    version: options.version || readVersion(extensionPath),
  });
  const content =
    platform === 'win32'
      ? renderWindowsShim(copied.cliPath)
      : renderPosixShim(copied.cliPath);
  writeFileAtomic(shimPath, content, platform === 'win32' ? 0o644 : 0o755);
  if (platform !== 'win32') {
    try {
      fs.chmodSync(shimPath, 0o755);
    } catch {
      /* best effort */
    }
  }

  const node = nodeExecutableOnPath(env.PATH, platform);
  const onPath = isDirectoryOnPath(dir, env.PATH, platform);
  const guidance = pathGuidance(dir, platform);

  // An earlier `flow` (for example an npm link) would shadow this launcher.
  const earlierFlow = findExecutable('flow', env.PATH, platform);
  const shadowedBy =
    earlierFlow &&
    normalizedPath(earlierFlow, platform) !== normalizedPath(shimPath, platform)
      ? earlierFlow
      : null;
  const mcpCommand = mcpCommandFor({
    appDataDir,
    env,
    platform,
    installDir: dir,
    forceExplicit: Boolean(shadowedBy),
  });

  return {
    ok: true,
    shimPath,
    installDir: dir,
    toolsDir: copied.toolsDir,
    cliPath: copied.cliPath,
    nodeFound: Boolean(node),
    onPath,
    shadowedBy,
    pathHint: guidance.onPathHint,
    pathCommand: guidance.command,
    mcpCommand,
  };
}

function claudeHome(env = process.env, platform = process.platform, homedir) {
  if (typeof env.CLAUDE_CONFIG_DIR === 'string' && env.CLAUDE_CONFIG_DIR.trim()) {
    return path.resolve(env.CLAUDE_CONFIG_DIR.trim());
  }
  const p = pathsFor(platform);
  return p.join(homedir || homeDir(env, platform), '.claude');
}

function installClaudeIntegration(options = {}) {
  const env = options.env || process.env;
  const platform = options.platform || process.platform;
  const home = options.claudeHome || claudeHome(env, platform, options.homedir);
  const force = options.force === true;
  const skillFile = path.join(home, 'skills', 'flow', 'SKILL.md');
  const commandFile = path.join(home, 'commands', 'flow-help.md');

  const existing = [skillFile, commandFile].filter((file) => fs.existsSync(file));
  if (existing.length > 0 && !force) {
    return {
      ok: false,
      conflict: true,
      files: existing,
      claudeHome: home,
    };
  }

  writeFileAtomic(skillFile, claude.SKILL_MARKDOWN, 0o644);
  writeFileAtomic(commandFile, claude.FLOW_HELP_COMMAND, 0o644);
  return { ok: true, files: [skillFile, commandFile], claudeHome: home };
}

/**
 * Arguments after `flow --` for an MCP client. Uses the installed shim when it
 * is on PATH; otherwise an explicit node + stable CLI path, which is more
 * reliable for MCP clients that do not inherit the shell PATH.
 */
function mcpLaunchArgs(options = {}) {
  const platform = options.platform || process.platform;
  const env = options.env || process.env;
  const appDataDir = options.appDataDir;
  const dir =
    options.installDir ||
    defaultInstallDir({
      platform,
      env,
      homedir: homeDir(env, platform),
    });
  if (
    options.forceExplicit !== true &&
    platform !== 'win32' &&
    isDirectoryOnPath(dir, env.PATH, platform)
  ) {
    return ['flow', 'mcp'];
  }
  const node = nodeExecutableOnPath(env.PATH, platform) || 'node';
  return [node, cliEntryPath(appDataDir), 'mcp'];
}

function mcpCommandFor(options = {}) {
  const platform = options.platform || process.platform;
  return `claude mcp add --scope user flow -- ${formatCommand(
    mcpLaunchArgs(options),
    platform,
  )}`;
}

module.exports = {
  SHIM_MARKER,
  findExecutable,
  nodeExecutableOnPath,
  isDirectoryOnPath,
  defaultInstallDir,
  installPaths,
  toolsDir,
  cliEntryPath,
  copyCliTools,
  refreshCliTools,
  installCli,
  installClaudeIntegration,
  mcpLaunchArgs,
  mcpCommandFor,
  formatCommand,
  claudeHome,
};
